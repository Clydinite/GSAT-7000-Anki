import json
import os
import csv
import time
from typing import List, Optional, Dict, Any
from google import genai
from dotenv import load_dotenv
from utils import BatchVerificationResult, VerificationResult, get_random_human_examples, SYSTEM_PROMPT

load_dotenv()
client = genai.Client(api_key=os.getenv("GEMINI_API_KEY"))

# --- Auditor Prompt ---
AUDITOR_SYSTEM_PROMPT = f"""
You are a VERY STRICT and SKEPTICAL GSAT English teacher auditing vocabulary flashcards. 
Your primary goal is to find errors. You are a "Critic AI" - your default assumption is that the card has quality issues, the cards are made by a student and is full of errors. Even the tiniest error is worth correcting for the good of the student on a test. For each of the cards, return one entry for HOW TO FIX THE ISSUE (e.g. Delete <pattern> ... </pattern> tags from sentence 1, do not remove the content inside; Add another sentence at the end using the collocation X). Write nothing in the comments if PASS. Be aware that there's often far more than a single issue per card, please list them ALL. You MUST be critical and strict.

### FAILURE CHECKLIST (FAIL if any are true):
- TAG_SCOPE_ERROR: Tagged a simple noun/object or common article.
- INCOMPLETE_PATTERN: Missing the key preposition or particle that makes the phrase a "collocation".
- DENSITY_ERROR: Versatile words (like 'account', 'leave', 'strike') have fewer than 3-4 example sentences.
- MISSING_EXAMPLES: Critical collocations are not covered.
- STYLE_MISMATCH: Sentences are too short or doesn't demonstrate the usage correctly (it should be able to be infered without knowing the word), or in any way that doesn't match the given standard examples.
- INSUFFICIENT_EXPLANATION: The explanation in any field is inadequate.
- VIOLATION_OF_SYSTEM_PROMPT: The flashcard generated by the AI doesn't follow the system prompt instructions.
- DIFFICULTY_MISMATCH: The sentence is too difficult/easy for the headword.
- MISSING_COLLOCATIONS: Does not include important usage patterns.
- AWKWARD_TRANSLATION: The Tradition Chinese is unnatural.
- SENTENCE_TOO_SHORT: The sentence is too short.
- OTHER_ISSUE: Other weird issues not already mentioned.

### ORIGINAL SYSTEM PROMPT (The "Creator's" Instructions, see if its work matches the system prompt. If not, FAIL):
{SYSTEM_PROMPT}
"""

def verify_batch(batch_items: List[Dict[str, str]], human_examples: List[Dict[str, Any]]) -> Optional[BatchVerificationResult]:
    few_shot = "### GOLD STANDARD EXAMPLES (PERFECT):\n"
    for ex in human_examples:
        few_shot += f"Word: {ex['headword']}\nJSON: {json.dumps(ex['response'], ensure_ascii=False)}\n---\n"

    batch_prompt = f"{few_shot}\n\n### BATCH TO AUDIT (Be very critical):\n"
    for i, item in enumerate(batch_items):
        batch_prompt += f"Card {i+1} ({item['headword']}):\n{item['response']}\n---\n"
    
    try:
        response = client.models.generate_content(
            model="gemma-4-31b-it",
            contents=batch_prompt,
            config={
                "system_instruction": AUDITOR_SYSTEM_PROMPT,
                "response_mime_type": "application/json",
                "response_schema": BatchVerificationResult,
                "temperature": 1.0,
                "thinking_config": {
                    "include_thoughts": False,
                    "thinking_level": "high"
                }
            } # type: ignore
        )
        return response.parsed # type: ignore
    except Exception as e:
        print(f"Error verifying batch: {e}")
        return None

def main() -> None:
    verify_level = 4

    human_examples = get_random_human_examples(10)
    file_path: str = f"data/raw/level{verify_level}.tsv"
    
    if not os.path.exists(file_path):
        print(f"File {file_path} not found.")
        return

    # Read all rows
    rows: List[Dict[str, str]] = []
    with open(file_path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f, delimiter="\t")
        fieldnames: Optional[List[str]] = reader.fieldnames
        rows = list(reader)

    if not fieldnames: return

    # Identify cards needing verification
    pending_indices = [i for i, r in enumerate(rows) if r.get("verification") == "none"]

    updated_count = 0
    batch_size = 25
    
    print(f"Auditing {len(pending_indices)} cards in batches of {batch_size} for Level {verify_level}...")
    
    for i in range(0, len(pending_indices), batch_size):
        batch_idx_chunk = pending_indices[i : i + batch_size]
        batch_items = [rows[idx] for idx in batch_idx_chunk]
        
        print(f"  Processing batch {i//batch_size + 1} ({len(batch_items)} cards)...")
        
        batch_result = verify_batch(batch_items, human_examples)
        
        if batch_result and len(batch_result.results) == len(batch_items):
            for result, row_idx in zip(batch_result.results, batch_idx_chunk):
                rows[row_idx]["verification"] = "ai_pass" if result.status == "pass" else "ai_fail"
                rows[row_idx]["comment"] = result.comment
                updated_count += 1
            print(f"    Batch complete. Total updated: {updated_count}")

            # Save progress incrementally
            with open(file_path, "w", encoding="utf-8", newline="") as f:
                writer = csv.DictWriter(f, fieldnames=fieldnames, delimiter="\t")
                writer.writeheader()
                writer.writerows(rows)
        else:
            if batch_result and len(batch_result.results) != len(batch_items):
                print(f"    Error: Batch size mismatch. Skipping batch.")
            else:
                print(f"    Error: API returned no results. Skipping batch.")
        
        time.sleep(4) # Be polite to API

    if updated_count > 0:
        print(f"Verification session finished. Successfully verified {updated_count} cards. {len(pending_indices) - updated_count} remaining.")
    else:
        print("No cards needed verification.")

if __name__ == "__main__":
    main()
